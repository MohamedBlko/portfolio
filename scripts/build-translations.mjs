import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const json = (file) => JSON.parse(readFileSync(resolve(root, file), 'utf8'));
const english = json('case-studies.json');
const french = json('locales/case-studies.fr.json');
const dictionary = {...json('locales/fr.json'), ...json('locales/media.fr.json')};
const normalize = (s) => s.replace(/\s+/g, ' ').trim();
function pair(en, fr, path) {
  if (typeof en === 'string' && typeof fr === 'string') dictionary[normalize(en)] = fr;
  else if (Array.isArray(en) && Array.isArray(fr)) {
    if (en.length !== fr.length) throw Error(`Translation length mismatch: ${path}`);
    en.forEach((value, index) => pair(value, fr[index], `${path}.${index}`));
  } else if (fr && typeof fr === 'object') {
    Object.keys(fr).forEach((key) => pair(en[key], fr[key], `${path}.${key}`));
  } else throw Error(`Missing translation: ${path}`);
}
for (const project of english) {
  const fr = french[project.slug];
  if (!fr) throw Error(`No French case: ${project.slug}`);
  pair(project, fr, project.slug);
  dictionary[project.tags.join(' / ')] = fr.tags.join(' / ');
  if (project.authored) continue;
  const folder = resolve(root, `assets/projects/${project.slug}`);
  mkdirSync(folder, {recursive:true});
  writeFileSync(resolve(folder, 'engineering-notes.fr.md'), `# ${fr.title}\n\n${fr.context} | ${fr.status}\n\n## Objectif\n${fr.objective}\n\n## Travail d'ingénierie\n${fr.work.map((s) => '- '+s).join('\n')}\n\n## Résultat\n${fr.outcome}\n\n## Portée et limites\n${fr.limits}\n\n## Références\n${fr.sources}\n`);
}
const media = json('assets/projects/media-index.json');
for (const items of Object.values(media)) for (const item of items) {
  const source = item.caption;
  const archive = source.match(/ Archive figure (\d+)\.$/);
  let base = source.replace(/ Archive figure \d+\.$/, '');
  const page = base.match(/ \(PDF page (\d+)\)\.$/);
  base = base.replace(/ \(PDF page \d+\)\.$/, '');
  const translated = dictionary[base];
  if (!translated) throw Error(`Missing media translation: ${base}`);
  dictionary[source] = `${translated}${page ? ` (page ${page[1]} du PDF).` : ''}${archive ? ` Figure d'archive ${archive[1]}.` : ''}`;
}
writeFileSync(resolve(root, 'translations.js'), `// Generated by scripts/build-translations.mjs. Edit locales/ instead.\nwindow.portfolioFrench = ${JSON.stringify(dictionary, null, 2)};\n`);
console.log(`Built ${Object.keys(dictionary).length} French strings and 16 French technical summaries.`);
